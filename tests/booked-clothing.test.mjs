import assert from 'node:assert/strict';
import {withBookedClothing} from '../app/lib/bookedClothing.mjs';
import {filterPayments} from '../app/lib/paymentFilters.mjs';
const players=[{id:'a',name:'Player A',team_id:'team'},{id:'b',name:'Player B',team_id:'other'}];
const payments=[{id:'fee',player_id:'a',amount:50,payment_kind:'membership',status:'paid'}];
const entry={id:'j',date:'2026-10-01',status:'posted'};
const economy={journal:[entry],payment_links:[{journal_id:'j',payment_id:'fee'}],settlement_selections:[{journal_id:'j',income_allocations:[{category:'clothing',amount:500}]}]};
const before=JSON.stringify({payments,economy});
const rows=withBookedClothing(payments,economy,players);
assert.equal(rows[1].player_id,'a');assert.equal(rows[1].amount,500);assert.equal(rows[1].read_only,true);
assert.equal(filterPayments(rows,{category:'clothing',status:'paid',team:'team',year:'2026',query:'Kläder och utrustning'},players).length,1);
assert.equal(filterPayments(rows,{category:'clothing',status:'pending'},players).length,0);
assert.equal(JSON.stringify({payments,economy}),before);
assert.equal(withBookedClothing(payments,{...economy,journal:[{...entry,status:'draft'}]},players).length,1);
assert.equal(withBookedClothing(payments,{...economy,journal:[entry,{id:'r',status:'posted',reversal_of:'j'}]},players).length,1);
const clothing={id:'clothing',player_id:'a',amount:500,status:'paid',payment_kind:'other',payment_category:'clothing'};
const linked={...economy,payment_links:[...economy.payment_links,{journal_id:'j',payment_id:'clothing'}]};
assert.equal(withBookedClothing([...payments,clothing],linked,players).length,2);
assert.equal(withBookedClothing(payments,{...economy,settlement_selections:[{journal_id:'j',income_allocations:[{category:'clothing',amount:850,player_id:'b'}]}]},players)[1].player_id,'b');
const two=[...payments,{id:'fee2',player_id:'b',amount:50,payment_kind:'membership',status:'paid'}];
assert.equal(withBookedClothing(two,{...economy,payment_links:[...economy.payment_links,{journal_id:'j',payment_id:'fee2'}]},players)[2].player_id,null);
console.log('PASS: booked clothing projection, combined filters, reversals, drafts, deduplication, person resolution and immutable inputs.');
