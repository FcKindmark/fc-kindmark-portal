import assert from 'node:assert/strict';
import {retryRead} from '../app/lib/retryRead.mjs';
const pause = async () => {};
let calls = 0;
assert.deepEqual(await retryRead(async () => ++calls < 3 ? {error:{message:'TypeError: Failed to fetch'}} : {data:['ok']}, pause), {data:['ok']});
assert.equal(calls, 3);
calls=0;
assert.equal(await retryRead(async () => {if(++calls===1)throw new TypeError('Failed to fetch');return 7;},pause),7);
assert.equal(calls,2);
calls=0;
const denied={error:{message:'permission denied',code:'42501'}};
assert.equal(await retryRead(async()=>{calls++;return denied;},pause),denied);
assert.equal(calls,1);
calls=0;
const unavailable={error:{message:'Failed to fetch'}};
assert.equal(await retryRead(async()=>{calls++;return unavailable;},pause),unavailable);
assert.equal(calls,3);
calls=0;
await assert.rejects(retryRead(async()=>{calls++;throw new TypeError('Failed to fetch');},pause),/Failed to fetch/);
assert.equal(calls,3);
await assert.rejects(retryRead(async()=>{throw Error('invalid data');},pause),/invalid data/);
console.log('Read retry tests passed: recovery, bounded failures, permission and application errors.');
